void main() {
  // --- Example 1: Print Your Name 5 Times Without Using Loop ---
  print("Ibrahem Qruea");
  print("Ibrahem Qruea");
  print("Ibrahem Qruea");
  print("Ibrahem Qruea");
  print("Ibrahem Qruea");
  print('*' * 40);

